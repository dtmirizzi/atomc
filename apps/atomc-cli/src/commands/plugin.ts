/** `atomc plugin {list,new}` — inspect loaded plugins and scaffold new ones. */
import { join, resolve } from "node:path";
import { MANIFEST_NAME_PATTERN, validatePluginManifest } from "@atomc/plugin-sdk";
import type { CliDeps, FsLike } from "../deps.js";
import { CliError } from "../errors.js";
import { emit } from "../output.js";

export interface PluginListOptions {
  json?: boolean;
  project?: string;
}

export interface PluginNewOptions {
  runtime?: "ts" | "python" | "both";
  dir?: string;
  force?: boolean;
  json?: boolean;
}

/** `atomc plugin list` — list plugins loaded by the daemon. */
export async function pluginList(deps: CliDeps, options: PluginListOptions = {}): Promise<number> {
  const projectRoot = resolve(deps.cwd, options.project ?? ".");
  const handle = await deps.ensureDaemon(projectRoot);
  try {
    const plugins = await handle.client.listPlugins();
    const payload = {
      count: plugins.length,
      plugins: plugins.map((plugin) => ({
        name: plugin.name,
        version: plugin.version,
        loaded: plugin.loaded,
        error: plugin.error,
      })),
    };
    emit(
      deps,
      options.json === true,
      payload,
      plugins.length === 0
        ? ["no plugins loaded"]
        : plugins.map(
            (p) =>
              `[${p.loaded ? "loaded" : "error"}] ${p.name}@${p.version}` +
              (p.error ? ` — ${p.error}` : ""),
          ),
    );
    return 0;
  } finally {
    await handle.client.close().catch(() => undefined);
  }
}

function manifestFor(name: string, runtime: "ts" | "python" | "both"): Record<string, unknown> {
  const python = `atomc_plugin_${name.replace(/-/g, "_")}:plugin`;
  const runtimeField =
    runtime === "python"
      ? { python }
      : runtime === "ts"
        ? { ts: "./dist/index.js" }
        : { python, ts: "./dist/index.js" };
  return {
    manifest_version: "0.1.0",
    name,
    version: "0.0.1",
    description: `${name} plugin for atomc`,
    atomc: ">=0.0.1 <0.2.0",
    runtime: runtimeField,
    watches: [{ id: `${name}:refresh`, ir: [`/ext/${name}`] }],
    produces: [`/ext/${name}`],
    gates: [
      {
        id: `gate:${name}.placeholder`,
        severity: "advisory",
        owner_agent: null,
        after: [`${name}:refresh`],
        handler: "check_placeholder",
      },
    ],
    tools: [],
    cli: [],
    ui: [],
  };
}

const TS_ENTRYPOINT = (name: string, manifest: Record<string, unknown>): string =>
  `import { defineAtomcPlugin, type GateResult } from "@atomc/plugin-sdk";

const manifest = ${JSON.stringify(manifest, null, 2)} as const;

/** ${name} plugin registration (generated by \`atomc plugin new\`). */
export const plugin = await defineAtomcPlugin({
  manifest,
  setup(ctx) {
    ctx.registerGate("check_placeholder", (context, gateId): GateResult => ({
      id: gateId,
      status: "SKIP",
      severity: "advisory",
      plugin: manifest.name,
      owner_agent: null,
      evaluated_at: new Date().toISOString(),
      ir_rev: 0,
      duration_ms: 0,
      summary: "placeholder gate — implement ${name} verification",
      evidence: [],
      suggestions: [],
      refs: [],
    }));
  },
});
`;

const TS_TEST = (name: string): string =>
  `import { describe, expect, it } from "vitest";
import { readFile } from "node:fs/promises";
import { validatePluginManifest } from "@atomc/plugin-sdk";

describe("${name} manifest", () => {
  it("validates against the frozen contract", async () => {
    const raw = await readFile(new URL("../atomc-plugin.json", import.meta.url), "utf8");
    const result = validatePluginManifest(JSON.parse(raw));
    expect(result.success).toBe(true);
  });
});
`;

function pythonEntrypoint(name: string, manifest: Record<string, unknown>): string {
  return `"""${name} plugin for atomc (generated by \`atomc plugin new\`)."""

from atomc_plugin_sdk import atomc_plugin

MANIFEST = ${JSON.stringify(manifest, null, 2).replace(/true/g, "True").replace(/false/g, "False").replace(/null/g, "None")}


@atomc_plugin(manifest=MANIFEST)
class Plugin:
    """${name} plugin handlers."""

    def check_placeholder(self, ctx, gate_id):
        return {
            "id": gate_id,
            "status": "SKIP",
            "severity": "advisory",
            "plugin": MANIFEST["name"],
            "owner_agent": None,
            "evaluated_at": "",
            "ir_rev": 0,
            "duration_ms": 0,
            "summary": "placeholder gate — implement ${name} verification",
            "evidence": [],
            "suggestions": [],
            "refs": [],
        }


plugin = Plugin()
`;
}

function pythonPyproject(name: string, moduleName: string): string {
  return `[build-system]
requires = ["hatchling>=1.33"]
build-backend = "hatchling.build"

[project]
name = "atomc-plugin-${name}"
version = "0.0.1"
description = "${name} plugin for atomc"
requires-python = ">=3.14,<3.15"
license = "Apache-2.0"
dependencies = ["atomc-plugin-sdk"]

[tool.hatch.build.targets.wheel]
packages = ["src/${moduleName}"]
`;
}

async function exists(fs: FsLike, path: string): Promise<boolean> {
  try {
    await fs.stat(path);
    return true;
  } catch {
    return false;
  }
}

/** `atomc plugin new <name>` — generate a validated plugin scaffold. */
export async function pluginNew(
  deps: CliDeps,
  name: string,
  options: PluginNewOptions = {},
): Promise<number> {
  if (!MANIFEST_NAME_PATTERN.test(name) || name.startsWith("plugin-")) {
    throw new CliError(`invalid plugin name "${name}" (kebab-case, no "plugin-" prefix)`, 1);
  }
  const runtime = options.runtime ?? "ts";
  const dir = resolve(deps.cwd, options.dir ?? name);
  if ((await exists(deps.fs, dir)) && !options.force) {
    const entries = await deps.fs.readdir(dir);
    if (entries.length > 0) {
      throw new CliError(`refusing to overwrite ${dir} (use --force)`, 1);
    }
  }

  const manifest = manifestFor(name, runtime);
  const validation = validatePluginManifest(manifest);
  if (!validation.success) {
    throw new CliError(
      `generated manifest failed validation: ${validation.issues
        .map((i) => `${i.path}: ${i.message}`)
        .join("; ")}`,
      1,
    );
  }

  await deps.fs.mkdir(dir, { recursive: true });
  const written: string[] = [];
  const write = async (rel: string, data: string): Promise<void> => {
    const path = join(dir, rel);
    await deps.fs.mkdir(join(path, ".."), { recursive: true }).catch(() => undefined);
    await deps.fs.writeFile(path, data);
    written.push(rel);
  };

  await write("atomc-plugin.json", `${JSON.stringify(manifest, null, 2)}\n`);
  if (runtime !== "python") {
    await write("src/index.ts", TS_ENTRYPOINT(name, manifest));
    await write("test/manifest.test.ts", TS_TEST(name));
  }
  if (runtime !== "ts") {
    const moduleName = `atomc_plugin_${name.replace(/-/g, "_")}`;
    await write(`python/src/${moduleName}/__init__.py`, pythonEntrypoint(name, manifest));
    await write("python/pyproject.toml", pythonPyproject(name, moduleName));
  }

  const payload = { created: true, name, runtime, dir, files: written };
  emit(deps, options.json === true, payload, [
    `created plugin "${name}" (${runtime}) in ${dir}`,
    ...written.map((f) => `  ${f}`),
    `next: register the path in your atomc config and restart the daemon`,
  ]);
  return 0;
}
