"""Location and use of the shared ``atomc-plugin.schema.json``.

The manifest JSON Schema is generated from the TypeScript Zod schema by WP-2.1 and committed at
``packages/plugin-sdk/schema/atomc-plugin.schema.json``. That artifact is the single cross-language
data contract: this Python SDK validates against it (Draft 2020-12) and never ships a second,
divergent schema.

Resolution order:

1. ``ATOMC_PLUGIN_SCHEMA`` environment variable, when set (path to a schema file).
2. A ``packages/plugin-sdk/schema/atomc-plugin.schema.json`` found by walking up from this file
   (the monorepo checkout, including git worktrees).
3. A copy packaged next to this module at ``_schema/atomc-plugin.schema.json`` if a distribution
   build elects to vendor it.

If none is present a :class:`SchemaNotFoundError` explains how to provide it.
"""

from __future__ import annotations

import json
import os
from functools import lru_cache
from pathlib import Path
from typing import Any

from jsonschema import Draft202012Validator  # type: ignore[import-untyped]
from jsonschema.exceptions import SchemaError  # type: ignore[import-untyped]

from .errors import ManifestError, SchemaNotFoundError

__all__ = [
    "SCHEMA_RELATIVE_PATH",
    "find_schema_path",
    "load_shared_schema",
    "pointer_from_path",
    "validate_against_schema",
]

SCHEMA_RELATIVE_PATH = Path("packages/plugin-sdk/schema/atomc-plugin.schema.json")

_ENV_VAR = "ATOMC_PLUGIN_SCHEMA"
_PACKAGED_RELATIVE = Path("_schema") / "atomc-plugin.schema.json"

_MISSING_HINT = (
    "could not locate the shared atomc plugin manifest JSON Schema "
    f"({SCHEMA_RELATIVE_PATH}). It is generated by WP-2.1 (packages/plugin-sdk/ts) and committed "
    f"at that path. Set the {_ENV_VAR} environment variable to an explicit schema file if you are "
    "running outside the monorepo checkout."
)


def find_schema_path(*, required: bool = True) -> Path | None:
    """Return the path to the shared manifest schema, or ``None`` when optional and missing."""
    override = os.environ.get(_ENV_VAR)
    if override:
        candidate = Path(override).expanduser()
        if candidate.is_file():
            return candidate
        if required:
            raise SchemaNotFoundError(f"{_ENV_VAR} points at {candidate}, which is not a file")
        return None

    here = Path(__file__).resolve()
    for parent in here.parents:
        candidate = parent / SCHEMA_RELATIVE_PATH
        if candidate.is_file():
            return candidate

    packaged = here.parent / _PACKAGED_RELATIVE
    if packaged.is_file():
        return packaged

    if required:
        raise SchemaNotFoundError(_MISSING_HINT)
    return None


@lru_cache(maxsize=1)
def load_shared_schema(path: str | None = None) -> dict[str, Any]:
    """Load and validate the shared schema document (cached per concrete path)."""
    resolved = Path(path) if path is not None else find_schema_path()
    assert resolved is not None  # find_schema_path(required=True) raises otherwise
    try:
        document = json.loads(resolved.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:  # pragma: no cover - guards a corrupt committed file
        raise SchemaNotFoundError(f"{resolved} is not valid JSON: {exc}") from exc
    if not isinstance(document, dict):  # pragma: no cover - guards a corrupt committed file
        raise SchemaNotFoundError(f"{resolved} must contain a JSON object")
    try:
        Draft202012Validator.check_schema(document)
    except SchemaError as exc:  # pragma: no cover - guards a corrupt committed file
        raise SchemaNotFoundError(f"{resolved} is not a valid JSON Schema: {exc.message}") from exc
    return document


def pointer_from_path(path: Any) -> str:
    """Render a jsonschema error path (iterable of keys/indices) as an RFC 6901 pointer."""
    parts: list[str] = []
    for segment in path:
        token = str(segment).replace("~", "~0").replace("/", "~1")
        parts.append(token)
    return "" if not parts else "/" + "/".join(parts)


def validate_against_schema(
    data: Any,
    schema: dict[str, Any] | None = None,
) -> list[ManifestError]:
    """Validate ``data`` against the shared Draft 2020-12 schema.

    Returns a list of :class:`ManifestError` ordered by document position; an empty list means
    the document is structurally valid.
    """
    active = schema if schema is not None else load_shared_schema()
    validator = Draft202012Validator(active)
    errors = sorted(
        validator.iter_errors(data),
        key=lambda err: [str(part) for part in err.absolute_path],
    )
    return [
        ManifestError(
            path=pointer_from_path(error.absolute_path),
            message=error.message,
            validator=error.validator,
        )
        for error in errors
    ]
