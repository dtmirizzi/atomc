"""Parsing and validation of ``atomc-plugin.json`` manifests.

The structural contract is the shared Draft 2020-12 JSON Schema generated by WP-2.1
(``packages/plugin-sdk/schema/atomc-plugin.schema.json``). This module validates the raw
document against that schema first, then parses it into strict Pydantic models for typed use
and applies the cross-field rules from ``docs/architecture/contracts/plugin-manifest.md`` that a
JSON Schema cannot always express (duplicate ids, pointer scopes, mutation permissions).

No plugin code is imported here and there are no import-time side effects.
"""

from __future__ import annotations

import json
from collections.abc import Mapping
from pathlib import Path
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, ValidationError, model_validator

from .errors import ManifestError, ManifestValidationError
from .schema import pointer_from_path, validate_against_schema

__all__ = [
    "ALLOWED_PRODUCES_NODES",
    "MANIFEST_VERSION",
    "AgentName",
    "CliCommand",
    "Gate",
    "PluginManifest",
    "Runtime",
    "Tool",
    "UiPanel",
    "Watch",
    "load_manifest",
    "validate_manifest",
]

MANIFEST_VERSION = "0.1.0"
"""The only ``manifest_version`` this SDK knows how to parse."""

SUPPORTED_MANIFEST_VERSIONS = frozenset({MANIFEST_VERSION})

ALLOWED_PRODUCES_NODES = frozenset(
    {
        "electrical",
        "layout",
        "keyboard",
        "firmware",
        "simulation",
        "mechanical",
        "sourcing",
        "fabrication",
        "orders",
        "gates",
        "provenance",
        "ext",
    }
)
"""Valid top-level IR nodes a plugin may declare under ``produces`` (``/meta`` is forbidden)."""

AgentName = Literal["ee-agent", "fw-agent", "mech-agent", "ops-agent"]
Severity = Literal["blocking", "advisory"]


class _PluginModel(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True, populate_by_name=True)


class Runtime(_PluginModel):
    """At least one runtime entrypoint; the path/target is loaded by the daemon, not the SDK."""

    python: str | None = None
    ts: str | None = None

    @model_validator(mode="after")
    def _require_one(self) -> Runtime:
        if not self.python and not self.ts:
            raise ValueError("at least one of 'python' or 'ts' runtime entrypoints is required")
        return self


class Watch(_PluginModel):
    id: str = Field(min_length=1)
    ir: list[str]
    files: list[str] = Field(default_factory=list)
    debounce_ms: int = Field(default=250, ge=0, le=60000)


class Gate(_PluginModel):
    id: str = Field(min_length=1)
    severity: Severity
    owner_agent: AgentName | None = None
    after: list[str] = Field(default_factory=list)
    handler: str = Field(min_length=1)


class Tool(_PluginModel):
    name: str = Field(min_length=1)
    description: str = ""
    # JSON Schema may be an object or a boolean (`true`/`false`), matching the shared schema.
    input_schema: dict[str, Any] | bool = Field(default_factory=dict)
    agents: list[AgentName] = Field(default_factory=list)
    mutates: bool = False
    handler: str = Field(min_length=1)


class CliCommand(_PluginModel):
    command: str = Field(min_length=1)
    description: str = ""
    handler: str = Field(min_length=1)


class UiPanel(_PluginModel):
    panel: str = Field(min_length=1)
    title: str = ""
    entry: str = Field(min_length=1)


class PluginManifest(_PluginModel):
    """A validated ``atomc-plugin.json`` document."""

    manifest_version: str
    name: str
    version: str
    description: str
    atomc: str
    runtime: Runtime
    watches: list[Watch]
    produces: list[str]
    gates: list[Gate]
    tools: list[Tool]
    cli: list[CliCommand]
    ui: list[UiPanel]

    @property
    def plugin_id(self) -> str:
        """Canonical IR plugin id, e.g. ``plugin:sourcing``."""
        return f"plugin:{self.name}"

    @property
    def handler_names(self) -> tuple[str, ...]:
        """All implementation export names declared by gates, tools and CLI commands."""
        names = [gate.handler for gate in self.gates]
        names += [tool.handler for tool in self.tools]
        names += [command.handler for command in self.cli]
        return tuple(names)


# ---------------------------------------------------------------------------
# Loading and validation
# ---------------------------------------------------------------------------

ManifestSource = "str | Path | Mapping[str, Any] | bytes"


def load_manifest(source: str | Path | Mapping[str, Any] | bytes) -> PluginManifest:
    """Load a manifest from a path, a mapping, or JSON text/bytes and validate it.

    A ``str``/``Path`` is treated as a filesystem path when it exists; otherwise a ``str`` is
    parsed as JSON text. Raises :class:`ManifestValidationError` on any contract violation.
    """
    data = _coerce_data(source)
    return validate_manifest(data)


def validate_manifest(data: Mapping[str, Any]) -> PluginManifest:
    """Validate an already-decoded manifest document and return typed models.

    Validation happens in three ordered stages so errors stay stable and path-oriented:

    1. Draft 2020-12 validation against the shared WP-2.1 schema.
    2. ``manifest_version`` support check.
    3. Pydantic parsing plus cross-field contract rules.
    """
    if not isinstance(data, Mapping):
        raise ManifestValidationError(
            [ManifestError(path="", message="manifest must be a JSON object")]
        )

    version = data.get("manifest_version")
    if version not in SUPPORTED_MANIFEST_VERSIONS:
        raise ManifestValidationError(
            [
                ManifestError(
                    path="/manifest_version",
                    message=(
                        f"unsupported manifest_version {version!r}; "
                        f"this SDK supports {MANIFEST_VERSION!r}"
                    ),
                    validator="const",
                )
            ]
        )

    schema_errors = validate_against_schema(data)
    if schema_errors:
        raise ManifestValidationError(schema_errors)

    try:
        manifest = PluginManifest.model_validate(data)
    except ValidationError as exc:
        raise ManifestValidationError(_pydantic_errors(exc)) from exc

    semantic = _semantic_errors(manifest)
    if semantic:
        raise ManifestValidationError(semantic)
    return manifest


def _coerce_data(source: str | Path | Mapping[str, Any] | bytes) -> Mapping[str, Any]:
    if isinstance(source, Mapping):
        return source
    if isinstance(source, bytes):
        return _decode_json(source.decode("utf-8"))
    if isinstance(source, Path):
        return _decode_json(source.read_text(encoding="utf-8"))
    if isinstance(source, str):
        candidate = Path(source)
        try:
            if candidate.is_file():
                return _decode_json(candidate.read_text(encoding="utf-8"))
        except OSError:  # pragma: no cover - overly long strings are not paths
            pass
        return _decode_json(source)
    raise TypeError(f"unsupported manifest source {type(source).__name__}")


def _decode_json(text: str) -> Mapping[str, Any]:
    try:
        parsed = json.loads(text)
    except json.JSONDecodeError as exc:
        raise ManifestValidationError(
            [ManifestError(path="", message=f"manifest is not valid JSON: {exc.msg}")]
        ) from exc
    if not isinstance(parsed, Mapping):
        raise ManifestValidationError(
            [ManifestError(path="", message="manifest must be a JSON object")]
        )
    return parsed


def _pydantic_errors(exc: ValidationError) -> list[ManifestError]:
    errors: list[ManifestError] = []
    for error in exc.errors():
        path = pointer_from_path(error.get("loc", ()))
        errors.append(
            ManifestError(
                path=path,
                message=error.get("msg", "invalid value"),
                validator=error.get("type"),
            )
        )
    return errors


def _semantic_errors(manifest: PluginManifest) -> list[ManifestError]:
    """Cross-field rules that JSON Schema cannot express.

    Structural rules (patterns, enums, required fields, pointer/node scopes) live in the shared
    WP-2.1 JSON Schema and are *not* duplicated here, so the Python SDK cannot diverge from the
    TypeScript SDK. What remains is uniqueness across sibling declarations (no ``uniqueItems`` in
    the generated schema) and the mutation/write-scope invariant.
    """
    errors: list[ManifestError] = []

    errors.extend(_duplicates("watch", "/watches", [w.id for w in manifest.watches]))
    errors.extend(_duplicates("gate", "/gates", [g.id for g in manifest.gates]))
    errors.extend(_duplicates("tool", "/tools", [t.name for t in manifest.tools]))
    errors.extend(_duplicates("CLI command", "/cli", [c.command for c in manifest.cli]))
    errors.extend(_duplicates("UI panel", "/ui", [u.panel for u in manifest.ui]))
    errors.extend(_produces_errors(manifest.produces))

    for index, tool in enumerate(manifest.tools):
        if tool.mutates and not manifest.produces:
            errors.append(
                ManifestError(
                    path=f"/tools/{index}/mutates",
                    message=(
                        f"mutating tool {tool.name!r} requires at least one declared "
                        "'produces' write scope"
                    ),
                    validator="mutation-scope",
                )
            )

    return errors


def _duplicates(kind: str, base: str, values: list[str]) -> list[ManifestError]:
    seen: dict[str, int] = {}
    errors: list[ManifestError] = []
    for index, value in enumerate(values):
        if value in seen:
            errors.append(
                ManifestError(
                    path=f"{base}/{index}",
                    message=(
                        f"duplicate {kind} identifier {value!r} "
                        f"(first declared at {base}/{seen[value]})"
                    ),
                    validator="unique",
                )
            )
        else:
            seen[value] = index
    return errors


def _produces_errors(produces: list[str]) -> list[ManifestError]:
    """Only uniqueness of ``produces`` scopes; node/pointer legality is in the shared schema."""
    errors: list[ManifestError] = []
    seen: set[str] = set()
    for index, pointer in enumerate(produces):
        if pointer in seen:
            errors.append(
                ManifestError(
                    path=f"/produces/{index}",
                    message=f"duplicate produces scope {pointer!r}",
                    validator="unique",
                )
            )
        seen.add(pointer)
    return errors
