/**
 * Code generator for @atomc/core-ir.
 *
 * Reads a JSON Schema (produced by WP-1.1's Pydantic models) and emits:
 *   - src/generated/types.ts : TypeScript types via json-schema-to-typescript
 *   - src/generated/zod.ts   : zod 4 runtime schemas via a hand-rolled emitter
 *
 * Usage:
 *   pnpm gen                    # generate against ../schema/system_ir.schema.json
 *   pnpm gen -- --schema <p>    # generate against an explicit schema
 *   pnpm gen -- --check         # fail (exit 1) if committed files are stale
 *
 * The emitter intentionally supports only the JSON Schema subset Pydantic v2 emits
 * (see docs/architecture/contracts/ir-schema.md). Anything outside the subset throws
 * loudly rather than silently producing a wrong validator.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const HERE = dirname(fileURLToPath(import.meta.url));
const PKG_DIR = resolve(HERE, "..");
const DEFAULT_SCHEMA = resolve(PKG_DIR, "../schema/system_ir.schema.json");
const STUB_SCHEMA = resolve(PKG_DIR, "test/stub.schema.json");
const TYPES_PATH = resolve(PKG_DIR, "src/generated/types.ts");
const ZOD_PATH = resolve(PKG_DIR, "src/generated/zod.ts");

const FILE_HEADER = "// Generated by scripts/gen.ts. Do not edit by hand.\n";

type SchemaObject = { [key: string]: unknown };
type Schema = boolean | SchemaObject;

function isObj(value: unknown): value is SchemaObject {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function jsonLiteral(value: unknown): string {
  return JSON.stringify(value) ?? "undefined";
}

function hasDefault(schema: Schema): boolean {
  return isObj(schema) && Object.hasOwn(schema, "default");
}

class ZodEmitter {
  private readonly names = new Map<string, string>();

  /** Map a JSON Pointer $ref to a stable TS identifier for its schema const. */
  refNameFor(ref: string): string {
    const key = this.defKey(ref);
    const existing = this.names.get(key);
    if (existing !== undefined) return existing;
    let base = key.replace(/[^A-Za-z0-9_$]/g, "_");
    if (!/^[A-Za-z_$]/.test(base)) base = `_${base}`;
    let name = `${base}Schema`;
    const used = new Set(this.names.values());
    let i = 1;
    while (used.has(name)) {
      name = `${base}${i}Schema`;
      i += 1;
    }
    this.names.set(key, name);
    return name;
  }

  private defKey(ref: string): string {
    const prefix = "#/$defs/";
    if (!ref.startsWith(prefix)) {
      throw new Error(`Unsupported $ref (only "#/$defs/..." supported): ${ref}`);
    }
    return decodeURIComponent(ref.slice(prefix.length).replace(/~1/g, "/").replace(/~0/g, "~"));
  }

  emit(schema: Schema): string {
    if (schema === true) return "z.unknown()";
    if (schema === false) return "z.never()";
    const s = schema as SchemaObject;
    if (typeof s.$ref === "string") return this.refNameFor(s.$ref);

    if (Array.isArray(s.allOf) && s.allOf.length > 0) {
      const parts = (s.allOf as Schema[]).map((sub) => this.emit(sub));
      if (parts.length === 1) return parts[0] as string;
      return parts.reduce((acc, part) => `z.intersection(${acc}, ${part})`);
    }

    let expr = this.emitCore(s);
    if (hasDefault(s)) expr += `.default(${jsonLiteral(s.default)})`;
    return expr;
  }

  private emitCore(s: SchemaObject): string {
    if (Object.hasOwn(s, "const")) {
      return `z.literal(${jsonLiteral(s.const)})`;
    }
    if (Array.isArray(s.enum)) return this.enumExpr(s.enum);

    const union = Array.isArray(s.anyOf) ? s.anyOf : Array.isArray(s.oneOf) ? s.oneOf : undefined;
    if (union) return this.unionExpr(union as Schema[]);

    const type = s.type;
    if (Array.isArray(type)) {
      const hasNull = type.includes("null");
      const nonNull = type.filter((t) => t !== "null");
      if (nonNull.length === 0) return "z.null()";
      if (nonNull.length === 1) {
        const base = this.typeExpr(nonNull[0] as string, s);
        return hasNull ? `${base}.nullable()` : base;
      }
      const parts = nonNull.map((t) => this.typeExpr(t as string, s));
      const base = `z.union([${parts.join(", ")}])`;
      return hasNull ? `${base}.nullable()` : base;
    }
    if (typeof type === "string") return this.typeExpr(type, s);

    // Untyped schema: objects with properties are still objects; otherwise unknown.
    if (isObj(s.properties) || s.additionalProperties === false) return this.typeExpr("object", s);
    return "z.unknown()";
  }

  private enumExpr(values: unknown[]): string {
    if (values.every((v) => typeof v === "string")) {
      return `z.enum([${values.map((v) => JSON.stringify(v)).join(", ")}] as const)`;
    }
    const parts = values.map((v) => `z.literal(${jsonLiteral(v)})`);
    return `z.union([${parts.join(", ")}])`;
  }

  private unionExpr(options: Schema[]): string {
    const isNull = (o: Schema) => isObj(o) && o.type === "null";
    const hasNull = options.some(isNull);
    const nonNull = options.filter((o) => !isNull(o));
    if (nonNull.length === 0) return "z.null()";
    let base =
      nonNull.length === 1
        ? (this.emit(nonNull[0] as Schema) as string)
        : `z.union([${nonNull.map((o) => this.emit(o as Schema)).join(", ")}])`;
    if (hasNull) base += ".nullable()";
    return base;
  }

  private typeExpr(type: string, s: SchemaObject): string {
    switch (type) {
      case "string": {
        let e = "z.string()";
        if (typeof s.minLength === "number") e += `.min(${s.minLength})`;
        if (typeof s.maxLength === "number") e += `.max(${s.maxLength})`;
        if (typeof s.pattern === "string") e += `.regex(new RegExp(${JSON.stringify(s.pattern)}))`;
        return e;
      }
      case "integer": {
        let e = "z.number().int()";
        e += this.bounds(s);
        return e;
      }
      case "number": {
        let e = "z.number()";
        e += this.bounds(s);
        return e;
      }
      case "boolean":
        return "z.boolean()";
      case "null":
        return "z.null()";
      case "array": {
        const items = this.emit(
          isObj(s.items) || typeof s.items === "boolean" ? (s.items as Schema) : true,
        );
        let e = `z.array(${items})`;
        if (typeof s.minItems === "number") e += `.min(${s.minItems})`;
        if (typeof s.maxItems === "number") e += `.max(${s.maxItems})`;
        return e;
      }
      case "object":
        return this.objectExpr(s);
      default:
        throw new Error(`Unsupported JSON Schema type: ${type}`);
    }
  }

  private bounds(s: SchemaObject): string {
    let e = "";
    if (typeof s.minimum === "number") e += `.min(${s.minimum})`;
    if (typeof s.maximum === "number") e += `.max(${s.maximum})`;
    if (typeof s.exclusiveMinimum === "number") e += `.gt(${s.exclusiveMinimum})`;
    if (typeof s.exclusiveMaximum === "number") e += `.lt(${s.exclusiveMaximum})`;
    return e;
  }

  private objectExpr(s: SchemaObject): string {
    const properties = isObj(s.properties) ? s.properties : undefined;
    const keys = properties ? Object.keys(properties) : [];
    if (properties && keys.length > 0) {
      const required = new Set(Array.isArray(s.required) ? (s.required as unknown[]) : []);
      const entries = keys.map((key) => {
        const prop = properties[key] as Schema;
        let expr = this.emit(prop);
        if (!required.has(key) && !hasDefault(prop)) expr += ".optional()";
        return `${JSON.stringify(key)}: ${expr}`;
      });
      let e = `z.object({ ${entries.join(", ")} })`;
      if (s.additionalProperties === false) e += ".strict()";
      return e;
    }
    if (isObj(s.additionalProperties)) {
      return `z.record(z.string(), ${this.emit(s.additionalProperties as Schema)})`;
    }
    return "z.record(z.string(), z.unknown())";
  }
}

function generateZod(schema: SchemaObject): string {
  const defs = isObj(schema.$defs) ? schema.$defs : {};
  const emitter = new ZodEmitter();
  const defLines: string[] = [];
  for (const key of Object.keys(defs)) {
    const ref = `#/$defs/${key}`;
    const name = emitter.refNameFor(ref);
    defLines.push(`const ${name} = z.lazy(() => ${emitter.emit(defs[key] as Schema)});`);
  }
  const root = emitter.emit(schema);
  return [
    FILE_HEADER,
    'import { z } from "zod";',
    'import type { SystemIR } from "./types.js";',
    "",
    ...defLines,
    "",
    `export const SystemIRSchema = ${root} as unknown as z.ZodType<SystemIR>;`,
    "",
  ].join("\n");
}

async function generateTypes(schema: SchemaObject, schemaPath: string): Promise<string> {
  const clone = JSON.parse(JSON.stringify(schema)) as SchemaObject;
  const compiled = await compile(clone, "SystemIR", {
    bannerComment: FILE_HEADER,
    additionalProperties: false,
    cwd: dirname(schemaPath),
    style: { semi: true, singleQuote: false, tabWidth: 2 },
  });
  return compiled;
}

function readSchema(schemaPath: string): SchemaObject {
  const parsed = JSON.parse(readFileSync(schemaPath, "utf8")) as unknown;
  if (!isObj(parsed)) throw new Error(`Schema at ${schemaPath} is not a JSON object`);
  return parsed;
}

function parseArgs(argv: string[]): { schemaPath: string; check: boolean } {
  let schemaPath = DEFAULT_SCHEMA;
  let check = false;
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === undefined) continue;
    if (arg === "--check") check = true;
    else if (arg === "--schema") {
      const next = argv[i + 1];
      if (!next) throw new Error("--schema requires a path");
      schemaPath = resolve(process.cwd(), next);
      i += 1;
    } else if (arg.startsWith("--schema=")) {
      schemaPath = resolve(process.cwd(), arg.slice("--schema=".length));
    } else {
      throw new Error(`Unknown argument: ${arg}`);
    }
  }
  return { schemaPath, check };
}

async function main(): Promise<void> {
  const { schemaPath: requested, check } = parseArgs(process.argv.slice(2));
  let schemaPath = requested;
  if (!existsSync(schemaPath)) {
    if (requested !== DEFAULT_SCHEMA) {
      throw new Error(`Schema not found: ${schemaPath}`);
    }
    console.warn(
      `[gen] Real schema not found at ${DEFAULT_SCHEMA}; falling back to stub ${STUB_SCHEMA}`,
    );
    schemaPath = STUB_SCHEMA;
  }

  const schema = readSchema(schemaPath);
  const typesOut = await generateTypes(schema, schemaPath);
  const zodOut = generateZod(schema);

  if (check) {
    const problems: string[] = [];
    for (const [path, expected] of [
      [TYPES_PATH, typesOut],
      [ZOD_PATH, zodOut],
    ] as const) {
      const actual = existsSync(path) ? readFileSync(path, "utf8") : "";
      if (actual !== expected) problems.push(path);
    }
    if (problems.length > 0) {
      console.error(`[gen] Generated output is stale:\n  ${problems.join("\n  ")}`);
      console.error("[gen] Run `pnpm --filter @atomc/core-ir gen` and commit the result.");
      process.exit(1);
    }
    console.log("[gen] Generated output is up to date.");
    return;
  }

  mkdirSync(dirname(TYPES_PATH), { recursive: true });
  writeFileSync(TYPES_PATH, typesOut);
  writeFileSync(ZOD_PATH, zodOut);
  console.log(`[gen] Wrote ${TYPES_PATH} and ${ZOD_PATH} from ${schemaPath}`);
}

main().catch((err: unknown) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
