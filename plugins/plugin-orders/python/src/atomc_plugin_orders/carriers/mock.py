"""The mock carrier: deterministic tracking timelines for fixture tracking numbers.

This is the only carrier that ships. It performs no network I/O and every :class:`TrackingUpdate`
it returns sets ``mock=True``; the plugin repeats that label in every tool result. Real carrier
adapters would implement :class:`~atomc_plugin_orders.carriers.base.Carrier` and be injected the
same way.
"""

from __future__ import annotations

from datetime import timedelta

from ..clock import Clock, SystemClock
from .base import TrackingEvent, TrackingUpdate

__all__ = ["MOCK_CARRIER_NAME", "MOCK_TIMELINES", "MockCarrier"]

MOCK_CARRIER_NAME = "mock"

#: Fixture tracking numbers -> ordered ``(status, days_ago, note)`` events. Events are anchored
#: to the injected clock so a test with a :class:`FixedClock` gets a byte-stable timeline.
MOCK_TIMELINES: dict[str, tuple[tuple[str, int, str], ...]] = {
    "MOCK-TRACK-1001": (
        ("shipped", 2, "departed mock fulfillment center"),
        ("delivered", 0, "delivered to mock mailbox"),
    ),
    "MOCK-TRACK-2002": (("shipped", 1, "in transit (mock)"),),
    "MOCK-TRACK-3003": (
        ("shipped", 5, "handed to mock carrier"),
        ("delivered", 3, "left at mock front door"),
    ),
}


class MockCarrier:
    """Deterministic, network-free :class:`~.base.Carrier` for tests and dry runs."""

    def __init__(self, clock: Clock | None = None) -> None:
        self._clock = clock or SystemClock()

    @property
    def name(self) -> str:
        return MOCK_CARRIER_NAME

    @property
    def mock(self) -> bool:
        return True

    def known_numbers(self) -> tuple[str, ...]:
        """Return the fixture tracking numbers this carrier knows."""
        return tuple(sorted(MOCK_TIMELINES))

    async def track(self, number: str) -> TrackingUpdate:
        """Return a deterministic timeline for a fixture number, or ``found=False`` for others."""
        timeline = MOCK_TIMELINES.get(number)
        if timeline is None:
            return TrackingUpdate(
                carrier=MOCK_CARRIER_NAME,
                number=number,
                mock=True,
                found=False,
                message=(
                    f"mock carrier has no fixture timeline for {number!r}; "
                    "known numbers: " + ", ".join(self.known_numbers())
                ),
            )
        now = self._clock.now()
        events = tuple(
            TrackingEvent(
                status=status,
                at=now - timedelta(days=days_ago),
                note=note,
            )
            for status, days_ago, note in timeline
        )
        return TrackingUpdate(
            carrier=MOCK_CARRIER_NAME,
            number=number,
            mock=True,
            found=True,
            events=events,
            message="timeline generated by the atomc mock carrier (no real shipment)",
        )
